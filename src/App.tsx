import { useState, useCallback, useEffect, useRef, useMemo } from 'react';
import { CleanLevelData, BoxItem, BoxNumType, BoxType, DragonSetup, TunnelSetup, ConveyorSetup } from './types/level';
import { DEMO_LEVEL, STARTER_LEVEL, EMPTY_LEVEL } from './data/demoLevel';
import { autoGenerateDragonSections } from './utils/dragonSolver';
import { BOX_DIMENSIONS } from './utils/colors';
import { sounds } from './utils/audio';
import { Toolbar } from './components/Toolbar';
import { Inspector, InspectorTab } from './components/Inspector';
import { Sidebar } from './components/Sidebar';
import { CanvasEditor } from './components/CanvasEditor';
import { DragonEditor } from './components/DragonEditor';
import { PlaytestView } from './components/PlaytestView';
import { ImportExportModal } from './components/ImportExportModal';
import { generateRandomTightLayout } from './utils/layoutGenerator';
import { LevelRail, LevelStatus } from './components/LevelRail';
import { auditLevel, AuditIssue } from './utils/levelAudit';
import { loadLevelList, saveLevelList, getDefaultLevelPack, LevelListState } from './utils/levelStore';

// Audit results per level object. Editing a level makes a new object, so only
// that level is checked again.
const auditCache = new WeakMap<CleanLevelData, AuditIssue[]>();
function auditCached(level: CleanLevelData): AuditIssue[] {
  let r = auditCache.get(level);
  if (!r) {
    try {
      r = auditLevel(level);
    } catch {
      r = [];
    }
    auditCache.set(level, r);
  }
  return r;
}

function App() {
  // Level list (saved in this browser; seeded with the built-in level pack)
  const [initialList] = useState<LevelListState>(() => loadLevelList());
  const [levelList, setLevelList] = useState<LevelListState>(initialList);
  const [inspectorTab, setInspectorTab] = useState<InspectorTab>('boxes');

  // The level currently open in the editor
  const [levelData, setLevelData] = useState<CleanLevelData>(() =>
    JSON.parse(JSON.stringify(initialList.levels[initialList.activeIndex]))
  );

  // Undo / Redo history for boxes
  const [history, setHistory] = useState<BoxItem[][]>([]);
  const [historyIdx, setHistoryIdx] = useState<number>(-1);

  // App UI State
  const [viewMode, setViewMode] = useState<'editor' | 'playtest'>('editor');
  const [selectedBoxIds, setSelectedBoxIds] = useState<number[]>([]);
  const [selectedTunnelId, setSelectedTunnelId] = useState<number | null>(null);
  const [selectedConveyorId, setSelectedConveyorId] = useState<number | null>(null);
  const [activeColor, setActiveColor] = useState<number>(1);
  const [activeNumType, setActiveNumType] = useState<BoxNumType>('Box6');
  const [activeBoxType, setActiveBoxType] = useState<BoxType>('Normal');
  const [gridSnap, setGridSnap] = useState<number>(0.25);
  const [showRays, setShowRays] = useState<boolean>(true);
  const [isImportExportOpen, setIsImportExportOpen] = useState<boolean>(false);

  // Keep the open level's edits in the list, and save the list (debounced)
  useEffect(() => {
    setLevelList((prev) => {
      if (prev.levels[prev.activeIndex] === levelData) return prev;
      const levels = [...prev.levels];
      levels[prev.activeIndex] = levelData;
      return { ...prev, levels };
    });
  }, [levelData]);

  const saveTimer = useRef<number | undefined>(undefined);
  useEffect(() => {
    window.clearTimeout(saveTimer.current);
    saveTimer.current = window.setTimeout(() => saveLevelList(levelList), 400);
    return () => window.clearTimeout(saveTimer.current);
  }, [levelList]);

  // Save right away when the tab is closed or reloaded, so the last edit is not lost.
  const latestList = useRef(levelList);
  useEffect(() => {
    latestList.current = levelList;
  }, [levelList]);
  useEffect(() => {
    const flush = () => saveLevelList(latestList.current);
    window.addEventListener('pagehide', flush);
    return () => window.removeEventListener('pagehide', flush);
  }, []);

  const openLevelInEditor = useCallback((level: CleanLevelData) => {
    setLevelData(level);
    setSelectedBoxIds([]);
    setSelectedTunnelId(null);
    setSelectedConveyorId(null);
    setHistory([]);
    setHistoryIdx(-1);
  }, []);

  const selectLevel = useCallback(
    (index: number) => {
      if (index < 0 || index >= levelList.levels.length || index === levelList.activeIndex) return;
      sounds.playPop();
      setLevelList((prev) => ({ ...prev, activeIndex: index }));
      openLevelInEditor(levelList.levels[index]);
    },
    [levelList, openLevelInEditor]
  );

  // Insert a level right after the current one and open it
  const addLevelAndSelect = useCallback(
    (level: CleanLevelData, atIndex?: number) => {
      const insertAt = atIndex ?? levelList.activeIndex + 1;
      setLevelList((prev) => {
        const levels = [...prev.levels];
        levels.splice(insertAt, 0, level);
        return { levels, activeIndex: insertAt };
      });
      openLevelInEditor(level);
    },
    [levelList.activeIndex, openLevelInEditor]
  );

  const nextFreeLevelId = () => levelList.levels.reduce((m, l) => Math.max(m, l.levelId || 0), 0) + 1;

  const handleAddLevel = () => {
    sounds.playPop();
    const blank = JSON.parse(JSON.stringify(EMPTY_LEVEL)) as CleanLevelData;
    blank.levelId = nextFreeLevelId();
    addLevelAndSelect(blank, levelList.levels.length);
  };

  const handleDuplicateLevel = (index: number) => {
    sounds.playPop();
    const copy = JSON.parse(JSON.stringify(levelList.levels[index])) as CleanLevelData;
    copy.levelId = nextFreeLevelId();
    addLevelAndSelect(copy, index + 1);
  };

  const handleDeleteLevel = (index: number) => {
    if (levelList.levels.length <= 1) return;
    sounds.playPop();
    const levels = levelList.levels.filter((_, i) => i !== index);
    let activeIndex = levelList.activeIndex;
    if (index < activeIndex) activeIndex -= 1;
    activeIndex = Math.min(activeIndex, levels.length - 1);
    const reopen = index === levelList.activeIndex;
    setLevelList({ levels, activeIndex });
    if (reopen) openLevelInEditor(levels[activeIndex]);
  };

  const handleMoveLevel = (index: number, delta: -1 | 1) => {
    const target = index + delta;
    if (target < 0 || target >= levelList.levels.length) return;
    const levels = [...levelList.levels];
    [levels[index], levels[target]] = [levels[target], levels[index]];
    let activeIndex = levelList.activeIndex;
    if (activeIndex === index) activeIndex = target;
    else if (activeIndex === target) activeIndex = index;
    setLevelList({ levels, activeIndex });
  };

  const handleImportLevels = (imported: CleanLevelData[], mode: 'append' | 'replace') => {
    if (mode === 'replace') {
      setLevelList({ levels: imported, activeIndex: 0 });
      openLevelInEditor(imported[0]);
    } else {
      const start = levelList.levels.length;
      setLevelList((prev) => ({ levels: [...prev.levels, ...imported], activeIndex: start }));
      openLevelInEditor(imported[0]);
    }
  };

  const handleResetToPack = () => {
    sounds.playPop();
    const levels = getDefaultLevelPack();
    setLevelList({ levels, activeIndex: 0 });
    openLevelInEditor(levels[0]);
  };

  // Push history on box change
  // History is updated outside the setLevelData updater: React may run an
  // updater twice, which used to bump the index twice and grey out Undo.
  const updateBoxesWithHistory = useCallback((newBoxes: BoxItem[], commitToHistory = true) => {
    if (commitToHistory) {
      const before = levelData.boxes;
      setHistory((currHist) => [...currHist.slice(0, historyIdx + 1), before]);
      setHistoryIdx(historyIdx + 1);
    }
    setLevelData((prev) => ({ ...prev, boxes: newBoxes }));
  }, [historyIdx, levelData.boxes]);

  // Undo
  const handleUndo = useCallback(() => {
    if (historyIdx >= 0 && history[historyIdx]) {
      sounds.playPop();
      const prevBoxes = history[historyIdx];
      setHistoryIdx((idx) => idx - 1);
      setLevelData((prev) => ({ ...prev, boxes: prevBoxes }));
    }
  }, [historyIdx, history]);

  // Redo
  const handleRedo = useCallback(() => {
    if (historyIdx + 1 < history.length) {
      sounds.playPop();
      const nextBoxes = history[historyIdx + 1];
      setHistoryIdx((idx) => idx + 1);
      setLevelData((prev) => ({ ...prev, boxes: nextBoxes }));
    }
  }, [historyIdx, history]);

  // Add Box tool
  const handleAddBox = (numType: BoxNumType, color: number, boxType: BoxType = 'Normal', angle: number = 0) => {
    sounds.playPop();
    const maxId = levelData.boxes.reduce((max, b) => Math.max(max, b.id), 0);
    const capacity = BOX_DIMENSIONS[numType].capacity;

    const newBox: BoxItem = {
      id: maxId + 1,
      x: 0,
      z: -2.0,
      angle,
      numType,
      capacity,
      color,
      boxType,
    };

    updateBoxesWithHistory([...levelData.boxes, newBox]);
    setSelectedBoxIds([newBox.id]);
    setSelectedTunnelId(null);
    setSelectedConveyorId(null);
  };

  const handleUpdateTunnels = (tunnels: TunnelSetup[]) => {
    setLevelData((prev) => ({ ...prev, tunnels }));
  };

  const handleUpdateConveyors = (conveyors: ConveyorSetup[]) => {
    setLevelData((prev) => ({ ...prev, conveyors }));
  };

  // Preset loader
  const handleLoadPreset = (presetName: string) => {
    sounds.playPop();
    let selectedPreset: CleanLevelData;
    if (presetName === 'starter') {
      selectedPreset = JSON.parse(JSON.stringify(STARTER_LEVEL));
    } else if (presetName === 'empty') {
      selectedPreset = JSON.parse(JSON.stringify(EMPTY_LEVEL));
    } else {
      selectedPreset = JSON.parse(JSON.stringify(DEMO_LEVEL));
    }

    // Auto-generate dragon for the preset
    const gen = autoGenerateDragonSections(
      selectedPreset.boxes,
      selectedPreset.slots?.unlockedCount ?? selectedPreset.slots?.count ?? 4,
      'normal'
    );
    if (gen.success) {
      selectedPreset.dragon.sections = gen.sections;
    }

    // Presets open as a new level in the list so the current level is kept
    addLevelAndSelect(selectedPreset);
  };

  // Dragon update
  const handleUpdateDragon = (updatedDragon: DragonSetup) => {
    setLevelData((prev) => ({ ...prev, dragon: updatedDragon }));
  };

  // Clear entire board (boxes, tunnels, conveyors, dragon configuration)
  const handleClearBoard = useCallback(() => {
    if (window.confirm('Are you sure you want to clear the entire board? All boxes, tunnels, conveyors, and dragon wool sections will be removed.')) {
      sounds.playPop();
      setHistory((currHist) => [...currHist.slice(0, historyIdx + 1), levelData.boxes]);
      setHistoryIdx((currIdx) => currIdx + 1);
      setLevelData((prev) => ({
        ...prev,
        boxes: [],
        tunnels: [],
        conveyors: [],
        dragon: {
          ...prev.dragon,
          sections: [],
        },
      }));
      setSelectedBoxIds([]);
      setSelectedTunnelId(null);
      setSelectedConveyorId(null);
    }
  }, [historyIdx, levelData.boxes]);

  // Randomize 49-box tight fit layout
  const handleRandomizeLayout = useCallback(() => {
    sounds.playPop();
    const newBoxes = generateRandomTightLayout(49);

    // Save previous state to history for undo
    setHistory((currHist) => [...currHist.slice(0, historyIdx + 1), levelData.boxes]);
    setHistoryIdx((currIdx) => currIdx + 1);

    // Auto-generate dragon wool sections for the new boxes
    const slotsCount = levelData.slots?.unlockedCount ?? levelData.slots?.count ?? 4;
    const tunnelBoxes = levelData.tunnels?.flatMap((t) => t.queue) || [];
    const conveyorBoxes = levelData.conveyors?.flatMap((c) => c.boxes) || [];
    const allBoxes = [...newBoxes, ...tunnelBoxes, ...conveyorBoxes];

    const gen = autoGenerateDragonSections(newBoxes, slotsCount, 'normal', allBoxes);
    const newSections = gen.success ? gen.sections : levelData.dragon.sections;

    setLevelData((prev) => ({
      ...prev,
      boxes: newBoxes,
      dragon: {
        ...prev.dragon,
        sections: newSections,
      },
    }));
    setSelectedBoxIds([]);
    setSelectedTunnelId(null);
    setSelectedConveyorId(null);
  }, [levelData, historyIdx]);

  // Global hotkeys (Undo/Redo, Escape playtest)
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (['INPUT', 'TEXTAREA'].includes((e.target as HTMLElement).tagName)) return;

      if ((e.ctrlKey || e.metaKey) && e.key === 'z') {
        e.preventDefault();
        if (e.shiftKey) {
          handleRedo();
        } else {
          handleUndo();
        }
      } else if ((e.ctrlKey || e.metaKey) && e.key === 'y') {
        e.preventDefault();
        handleRedo();
      } else if (e.key === 'Escape' && viewMode === 'playtest') {
        setViewMode('editor');
      }
    };

    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [handleUndo, handleRedo, viewMode]);

  const statuses = useMemo<LevelStatus[]>(
    () =>
      levelList.levels.map((l) => {
        const iss = auditCached(l);
        return iss.some((i) => i.severity === 'error') ? 'bad' : iss.length ? 'warn' : 'ok';
      }),
    [levelList.levels]
  );
  const issues = auditCached(levelData);

  const selectBoxes = (ids: number[]) => {
    setSelectedBoxIds(ids);
    if (ids.length > 0) {
      setSelectedTunnelId(null);
      setSelectedConveyorId(null);
      if (inspectorTab === 'level' || inspectorTab === 'json') setInspectorTab('boxes');
    }
  };
  const selectTunnel = (id: number | null) => {
    setSelectedTunnelId(id);
    if (id !== null) {
      setSelectedBoxIds([]);
      setSelectedConveyorId(null);
      if (inspectorTab === 'level' || inspectorTab === 'json') setInspectorTab('boxes');
    }
  };
  const selectConveyor = (id: number | null) => {
    setSelectedConveyorId(id);
    if (id !== null) {
      setSelectedBoxIds([]);
      setSelectedTunnelId(null);
      if (inspectorTab === 'level' || inspectorTab === 'json') setInspectorTab('boxes');
    }
  };

  const startPlaytest = () => {
    sounds.playWhoosh();
    setViewMode('playtest');
  };

  return (
    <div className="app text-slate-100">
      <LevelRail
        levels={levelList.levels}
        activeIndex={levelList.activeIndex}
        statuses={statuses}
        onSelect={selectLevel}
        onAdd={handleAddLevel}
        onDuplicate={handleDuplicateLevel}
        onDelete={handleDeleteLevel}
        onMove={handleMoveLevel}
        onImportLevels={handleImportLevels}
        onResetToPack={handleResetToPack}
      />

      <main className="mid">
        <Toolbar
          levelData={levelData}
          levelIndex={levelList.activeIndex}
          levelCount={levelList.levels.length}
          viewMode={viewMode}
          onSetViewMode={setViewMode}
          onPrevLevel={() => selectLevel(levelList.activeIndex - 1)}
          onNextLevel={() => selectLevel(levelList.activeIndex + 1)}
          canUndo={historyIdx >= 0 && !!history[historyIdx]}
          canRedo={historyIdx + 1 < history.length}
          onUndo={handleUndo}
          onRedo={handleRedo}
          gridSnap={gridSnap}
          onSetGridSnap={setGridSnap}
          showRays={showRays}
          onSetShowRays={setShowRays}
          onRandomizeLayout={handleRandomizeLayout}
          onClearBoard={handleClearBoard}
          onOpenImportExport={() => setIsImportExportOpen(true)}
          onImportLevel={(imported) => addLevelAndSelect(imported)}
        />
        <div className="stage">
          {viewMode === 'playtest' ? (
            // Keyed by level so switching levels restarts the playtest.
            <PlaytestView key={levelList.activeIndex} levelData={levelData} onExit={() => setViewMode('editor')} />
          ) : (
            <div className="flex-1 relative overflow-hidden">
              <CanvasEditor
                boxes={levelData.boxes}
                selectedBoxIds={selectedBoxIds}
                onSelectBoxes={selectBoxes}
                onUpdateBoxes={updateBoxesWithHistory}
                activeColor={activeColor}
                activeNumType={activeNumType}
                gridSnap={gridSnap}
                showRays={showRays}
                dragon={levelData.dragon}
                slots={levelData.slots}
                tunnels={levelData.tunnels || []}
                onUpdateTunnels={handleUpdateTunnels}
                selectedTunnelId={selectedTunnelId}
                onSelectTunnel={selectTunnel}
                conveyors={levelData.conveyors || []}
                onUpdateConveyors={handleUpdateConveyors}
                selectedConveyorId={selectedConveyorId}
                onSelectConveyor={selectConveyor}
              />
            </div>
          )}
        </div>
      </main>

      <Inspector
        tab={inspectorTab}
        onSetTab={setInspectorTab}
        levelData={levelData}
        levels={levelList.levels}
        activeIndex={levelList.activeIndex}
        issues={issues}
        onUpdateLevelData={(updater) => setLevelData(updater)}
        onLoadPreset={handleLoadPreset}
        onShowBoxes={(ids) => {
          setViewMode('editor');
          setSelectedBoxIds(ids);
          setSelectedTunnelId(null);
          setSelectedConveyorId(null);
        }}
        onOpenLevel={selectLevel}
        boxesPane={
          <Sidebar
            boxes={levelData.boxes}
            selectedBoxIds={selectedBoxIds}
            onSelectBoxes={selectBoxes}
            onUpdateBoxes={updateBoxesWithHistory}
            activeColor={activeColor}
            setActiveColor={setActiveColor}
            activeNumType={activeNumType}
            setActiveNumType={setActiveNumType}
            activeBoxType={activeBoxType}
            setActiveBoxType={setActiveBoxType}
            onAddBox={handleAddBox}
            tunnels={levelData.tunnels || []}
            onUpdateTunnels={handleUpdateTunnels}
            selectedTunnelId={selectedTunnelId}
            onSelectTunnel={selectTunnel}
            conveyors={levelData.conveyors || []}
            onUpdateConveyors={handleUpdateConveyors}
            selectedConveyorId={selectedConveyorId}
            onSelectConveyor={selectConveyor}
          />
        }
        dragonPane={
          <DragonEditor
            boxes={levelData.boxes}
            dragon={levelData.dragon}
            slotsCount={levelData.slots?.unlockedCount ?? levelData.slots?.count ?? 4}
            tunnels={levelData.tunnels || []}
            conveyors={levelData.conveyors || []}
            onUpdateDragon={handleUpdateDragon}
            onStartPlaytest={startPlaytest}
          />
        }
      />

      <ImportExportModal
        isOpen={isImportExportOpen}
        onClose={() => setIsImportExportOpen(false)}
        levelData={levelData}
        onImportLevel={(imported) => addLevelAndSelect(imported)}
      />
    </div>
  );
}

export default App;
